/**
 * [EN] The example custom-tab-bar's route sync (`cyl_syncWithRoute`) on a real runtime where a page can show before its tab
 *      bar exists: a null `selectComponent` (the cyl-tab-bar is not mounted yet) or a bar without configuration must not throw
 *      and must not lose the selection; the route waits and is applied when the bar has its tabs.
 * [CN] 示例 custom-tab-bar 的路由同步（`cyl_syncWithRoute`），在真实运行时中页面可能先于其 TabBar 显示：`selectComponent` 为 null
 *      （cyl-tab-bar 尚未挂载）或 TabBar 还没有配置时不能抛错，也不能丢失选中项；路由等待，TabBar 有了 Tab 后再应用。
 */
const test = require('node:test')
const assert = require('node:assert/strict')
const path = require('node:path')

function cylCustomTabBar() {
  global.wx = { getSystemInfoSync: () => ({ theme: 'light' }), getAppBaseInfo: () => ({ theme: 'light' }) }
  global.getApp = () => ({ globalData: {} })
  let definition
  global.Component = (d) => { definition = d }
  const file = path.join(__dirname, '../example/miniprogram/custom-tab-bar/index.js')
  delete require.cache[file]
  // [EN] `shared/animations.js` is generated by `npm run setup` and is not in the repository: stand in for it, so the test
  //      runs with plain `npm test` (as in CI).
  // [CN] `shared/animations.js` 由 `npm run setup` 生成，不在仓库中：这里用替身，使 `npm test` 单独即可运行（与 CI 一致）。
  const Module = require('node:module')
  const load = Module._load
  Module._load = function (request, ...rest) {
    return request === '../shared/animations' ? { installed: 'lottie', files: [] } : load.call(this, request, ...rest)
  }
  try {
    require(file)
  } finally {
    Module._load = load
  }
  delete global.Component
  return { data: { ...definition.data }, bar: null, ...definition.methods, selectComponent() { return this.bar } }
}

test('a route synced before the cyl-tab-bar is mounted does not throw and is applied when it appears', () => {
  const customTabBar = cylCustomTabBar()
  assert.doesNotThrow(() => customTabBar.cyl_syncWithRoute('pages/message/index'))
  const selected = []
  customTabBar.bar = { cylSelectPage: (page) => { selected.push(page); return true } }
  customTabBar.cyl_applyPendingPage()
  assert.deepEqual(selected, ['message'])
  customTabBar.cyl_applyPendingPage()
  assert.deepEqual(selected, ['message'], 'applied once')
})

test('a bar without configuration (no tab for the page yet) keeps the route waiting', () => {
  const customTabBar = cylCustomTabBar()
  let ready = false
  customTabBar.bar = { cylSelectPage: () => ready }
  customTabBar.cyl_syncWithRoute('pages/me/index')
  assert.equal(customTabBar.cylPendingPage, 'me')
  ready = true
  customTabBar.cyl_applyPendingPage()
  assert.equal(customTabBar.cylPendingPage, '')
})

test('a route that is not a tab page path is ignored', () => {
  const customTabBar = cylCustomTabBar()
  customTabBar.bar = { cylSelectPage: () => assert.fail('no page to select') }
  assert.doesNotThrow(() => customTabBar.cyl_syncWithRoute('other/path'))
  assert.doesNotThrow(() => customTabBar.cyl_syncWithRoute(undefined))
})
