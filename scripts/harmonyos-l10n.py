#!/usr/bin/env python3
"""[EN] Localization of the HarmonyOS port (CrossPlatform/harmonyos-cyltabbar).

Collects every key the HarmonyOS sources pass to `CYLLocalizedString('…')` or mark with `cyl_localizationKey('…')`, then
writes the string resources of the cyltabbar module, one folder per language:
  - the translation of each key comes from the iOS bundle
    (CYLTabBarController/Resources/CYLTabBarController.bundle/<lang>.lproj/CYLTabBarController.strings),
  - keys only the HarmonyOS port has come from scripts/harmonyos-l10n.json ({"<lang>": {"<key>": "<text>"}}),
  - a language without a translation falls back to English, English to the key.
It also writes cyltabbar/src/main/ets/CYLLocalizationTable.ets (key -> resource name) and the tab titles of the entry
module (tab_* strings) for every language.

    python3 scripts/harmonyos-l10n.py           # writes the resources
    python3 scripts/harmonyos-l10n.py --check   # fails when they are stale or a key has no English text

[CN] 鸿蒙端本地化：收集鸿蒙源码中传给 `CYLLocalizedString('…')` 或用 `cyl_localizationKey('…')` 标记的 key，按语言写出 cyltabbar 模块的字符串资源。
译文来自 iOS 资源包；只有鸿蒙端有的 key 来自 scripts/harmonyos-l10n.json；没有译文时回退到英文，英文没有时为 key。
"""
import glob
import hashlib
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HM = os.path.join(ROOT, 'CrossPlatform', 'harmonyos-cyltabbar')
BUNDLE = os.path.join(ROOT, 'CYLTabBarController', 'Resources', 'CYLTabBarController.bundle')
EXTRA = os.path.join(ROOT, 'scripts', 'harmonyos-l10n.json')
TABLE = os.path.join(HM, 'cyltabbar', 'src', 'main', 'ets', 'CYLLocalizationTable.ets')
LIB_RES = os.path.join(HM, 'cyltabbar', 'src', 'main', 'resources')
ENTRY_RES = os.path.join(HM, 'entry', 'src', 'main', 'resources')

# [EN] iOS .lproj -> HarmonyOS resource qualifier. [CN] iOS 语言目录 -> 鸿蒙资源限定词。
QUALIFIERS = {
    'en': 'base', 'zh-Hans': 'zh_CN', 'zh-Hant': 'zh_TW', 'pt-BR': 'pt_BR',
}
# [EN] The entry module's tab titles and their keys. [CN] entry 模块的 Tab 标题及其 key。
ENTRY_STRINGS = {'tab_home': '首页', 'tab_nearby': '同城', 'tab_messages': '消息', 'tab_me': '我的', 'tab_post': '发布',
                 'tab_refresh': '刷新'}
ENTRY_FIXED = {'module_desc': 'CYLTabBarController example', 'ability_desc': 'CYLTabBarController example',
               'app_name': 'CYLTabBar'}


def parse_strings(path):
    text = open(path, encoding='utf-8', errors='replace').read()
    out = {}
    for m in re.finditer(r'^"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)";', text, re.M):
        unescape = lambda v: v.replace('\\"', '"').replace('\\n', '\n').replace('\\\\', '\\')
        out[unescape(m.group(1))] = unescape(m.group(2))
    return out


def used_keys():
    keys = set()
    pattern = re.compile(r"(?:CYLLocalizedString|cyl_localizationKey)\(\s*'((?:[^'\\]|\\.)*)'")
    for path in glob.glob(os.path.join(HM, '*', 'src', 'main', 'ets', '**', '*.ets'), recursive=True):
        for m in pattern.finditer(open(path, encoding='utf-8').read()):
            keys.add(m.group(1).replace("\\'", "'"))
    return sorted(keys)


def resource_name(key):
    return 'cyl_l10n_' + hashlib.md5(key.encode('utf-8')).hexdigest()[:12]


def outputs():
    keys = used_keys()
    extra = json.load(open(EXTRA, encoding='utf-8')) if os.path.exists(EXTRA) else {}
    languages = sorted(d[:-6] for d in os.listdir(BUNDLE) if d.endswith('.lproj'))
    tables = {lang: parse_strings(os.path.join(BUNDLE, lang + '.lproj', 'CYLTabBarController.strings')) for lang in languages}
    english = dict(tables.get('en', {}))
    english.update(extra.get('en', {}))
    files = {}
    problems = []
    for lang in languages:
        qualifier = QUALIFIERS.get(lang, lang.replace('-', '_'))
        table = dict(tables[lang])
        table.update(extra.get(lang, {}))
        strings = []
        for key in keys:
            text = table.get(key) or english.get(key)
            if text is None:
                if lang == 'en':
                    problems.append(key)
                text = key
            strings.append({'name': resource_name(key), 'value': text})
        files[os.path.join(LIB_RES, qualifier, 'element', 'string.json')] = json.dumps({'string': strings}, ensure_ascii=False, indent=2) + '\n'
        entry = [{'name': n, 'value': table.get(k) or english.get(k, k)} for n, k in ENTRY_STRINGS.items()]
        entry += [{'name': n, 'value': v} for n, v in ENTRY_FIXED.items()]
        files[os.path.join(ENTRY_RES, qualifier, 'element', 'string.json')] = json.dumps({'string': entry}, ensure_ascii=False, indent=2) + '\n'
    lines = ['/**',
             ' * [EN] Generated by scripts/harmonyos-l10n.py; do not edit by hand. Localization key -> string resource name.',
             ' * [CN] 由 scripts/harmonyos-l10n.py 生成；请勿手动编辑。本地化 key -> 字符串资源名。',
             ' */',
             'export const CYL_LOCALIZATION_KEYS: Map<string, string> = new Map<string, string>(['] + \
            ['  [%s, %s],' % (json.dumps(k, ensure_ascii=False).replace("'", "\\'"), json.dumps(resource_name(k))) for k in keys] + ['']
    lines[-1] = ']);'
    files[TABLE] = '\n'.join(lines) + '\n'
    return files, problems


def main():
    files, problems = outputs()
    stale = [p for p, text in files.items() if not os.path.exists(p) or open(p, encoding='utf-8').read() != text]
    if '--check' in sys.argv:
        if problems:
            print('keys without English text (add them to scripts/harmonyos-l10n.json "en"):', problems)
        if stale:
            print('stale localization files, run python3 scripts/harmonyos-l10n.py:', [os.path.relpath(p, ROOT) for p in stale])
        return 1 if problems or stale else 0
    for path, text in files.items():
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'w', encoding='utf-8', newline='\n') as handle:
            handle.write(text)
    print('keys', len(used_keys()), 'files', len(files), 'without English', len(problems))
    for key in problems:
        print('  missing English:', key)
    return 0


if __name__ == '__main__':
    sys.exit(main())
