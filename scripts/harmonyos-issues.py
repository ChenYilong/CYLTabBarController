#!/usr/bin/env python3
"""[EN] The issue list of the HarmonyOS port, found in emulator screenshots (docs/HarmonyOS-Issues.md).

One row per issue in scripts/harmonyos-issues.json: {"id", "title", "evidence", "cause", "fix", "status", "scope"}.
Statuses:
  - "TODO"                          found, not fixed;
  - "TODO need 模拟器截图验证"        fixed in code without an emulator, waiting for a screenshot check;
  - "DONE (<screenshot>)"           checked on the emulator or a device.
Score = 100 * (rows whose status is not exactly "TODO") / all rows; no "TODO" row left is 100 (full score). The final
check (every row DONE) happens when the screenshots are taken again.

    python3 scripts/harmonyos-issues.py           # writes docs/HarmonyOS-Issues.md
    python3 scripts/harmonyos-issues.py --check   # fails when the document is stale or a status is unknown

[CN] 鸿蒙端在模拟器截图中发现的问题清单。每个问题一行；状态：TODO（未修复）、TODO need 模拟器截图验证（已在无模拟器条件下修复，待截图验证）、
DONE（已在模拟器或真机验证）。完成率 = 100 × 状态不是 "TODO" 的行 / 全部行；没有 "TODO" 行即满分。
"""
import importlib.util
import json
import os
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, 'scripts', 'harmonyos-issues.json')
DOC = os.path.join(ROOT, 'docs', 'HarmonyOS-Issues.md')
FIXED = 'TODO need 模拟器截图验证'


def valid(status):
    return status == 'TODO' or status == FIXED or status.startswith('DONE')


def document(rows):
    done = sum(1 for r in rows if r['status'] != 'TODO')
    verified = sum(1 for r in rows if r['status'].startswith('DONE'))
    score = int(100 * done / len(rows)) if rows else 100
    out = ['# 鸿蒙端问题清单 / HarmonyOS issues', '', '<!-- bound-classes: none -->', '',
           '<!-- Generated by scripts/harmonyos-issues.py from scripts/harmonyos-issues.json; do not edit by hand. -->',
           '<!-- 由 scripts/harmonyos-issues.py 根据 scripts/harmonyos-issues.json 生成；请勿手动编辑。 -->', '',
           '| 中文 | English |', '|:---|:---|',
           '| 来源：模拟器截图（docs/assets/harmonyos-*.png / .jpeg，Mate 70 Pro 模拟器，HarmonyOS 6.0.1 API 21）。每发现一个问题新增一行，包括本仓库其他目录与其他仓库的问题。 | Source: emulator screenshots (docs/assets/harmonyos-*.png / .jpeg, Mate 70 Pro emulator, HarmonyOS 6.0.1 API 21). One row per issue found, including issues in other folders of this repository and in other repositories. |',
           '| 状态：`TODO` 未修复；`%s` 已修复、待模拟器截图验证；`DONE (<截图>)` 已验证。 | Status: `TODO` not fixed; `%s` fixed, waiting for an emulator screenshot; `DONE (<screenshot>)` checked. |' % (FIXED, FIXED),
           '| **打分：%d / 100**（%d / %d 个问题不再是 TODO；已截图验证 %d）。没有 `TODO` 行即满分。 | **Score: %d / 100** (%d of %d issues no longer TODO; %d checked with a screenshot). No `TODO` row left is the full score. |'
           % (score, done, len(rows), verified, score, done, len(rows), verified), '',
           '| # | 状态 / Status | 范围 / Scope | 问题 / Issue | 证据 / Evidence | 原因 / Cause | 修复 / Fix |',
           '|:---|:---|:---|:---|:---|:---|:---|']
    for r in rows:
        cells = [str(r['id']), r['status'], r['scope'], r['title'], r['evidence'], r['cause'], r['fix']]
        out.append('| ' + ' | '.join(c.replace('|', '\\|').replace('\n', ' ') for c in cells) + ' |')
    return '\n'.join(out) + '\n', score


def with_navigation(text):
    """
    [EN] The document as scripts/update-docs-navigation.py leaves it (contents block and class binding block), so the two
         generators agree and its --check in CI passes after this script runs.
    [CN] 套用 scripts/update-docs-navigation.py 的目录块与类绑定块后的文档，使两个生成器结果一致，CI 中它的 --check 能通过。
    """
    spec = importlib.util.spec_from_file_location('cyl_docs_navigation', os.path.join(ROOT, 'scripts', 'update-docs-navigation.py'))
    navigation = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(navigation)
    with tempfile.NamedTemporaryFile('w', suffix='.md', delete=False, encoding='utf-8', newline='\n') as handle:
        handle.write(text)
    try:
        _, updated = navigation.update_page(handle.name)
    finally:
        os.remove(handle.name)
    lines = updated.split('\n')
    lines = navigation.apply_binding_block(lines, navigation.binding_rows([], {}, os.path.basename(DOC)))
    return '\n'.join(lines)


def main():
    rows = json.load(open(DATA, encoding='utf-8'))
    bad = [r['id'] for r in rows if not valid(r['status'])]
    text, score = document(rows)
    text = with_navigation(text)
    if '--check' in sys.argv:
        current = open(DOC, encoding='utf-8').read() if os.path.exists(DOC) else ''
        if bad:
            print('unknown status in rows', bad)
        if current != text:
            print('docs/HarmonyOS-Issues.md is stale: run python3 scripts/harmonyos-issues.py')
        return 1 if bad or current != text else 0
    with open(DOC, 'w', encoding='utf-8', newline='\n') as handle:
        handle.write(text)
    print('score', score)
    return 0


if __name__ == '__main__':
    sys.exit(main())
