#!/usr/bin/env python3
"""
[EN] Writes the Android library's texts that iOS reads from its string tables (the badge and plus button accessibility
     texts) into Android resources, one values-<language> folder per iOS .lproj folder, so both platforms say the same
     thing in every language. Run it after changing CYLTabBarController.bundle/*.lproj; `--check` fails when a file is
     out of date (for CI).
[CN] 把 iOS 从字符串表读取的 Android 库文字（角标与 PlusButton 的无障碍文字）写入 Android 资源，每个 iOS .lproj 文件夹对应一个
     values-<语言> 文件夹，使两个平台在每种语言中说法一致。修改 CYLTabBarController.bundle/*.lproj 后运行；`--check` 在文件过期时失败（用于 CI）。
"""
import os
import re
import sys
from xml.sax.saxutils import escape

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BUNDLE = os.path.join(ROOT, 'CYLTabBarController', 'Resources', 'CYLTabBarController.bundle')
RES = os.path.join(ROOT, 'Example-Android', 'cyltabbar', 'src', 'main', 'res')
FILE = 'cyl_localized_strings.xml'
# [EN] Android resource name -> iOS key. [CN] Android 资源名 -> iOS 键。
STRINGS = {
    'cyl_badge_new_content': '有新内容',
    'cyl_badge_new_messages': '%@ 条新消息',
    'cyl_plus_button': '加号按钮',
    'cyl_badge_new_lowercase': 'new',
    'cyl_badge_new_uppercase': 'NEW',
}
PAIR = re.compile(r'^"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)";', re.M)


def folder(language):
    """[EN] values-<qualifier> of an iOS language: BCP 47 form, e.g. b+zh+Hans. [CN] iOS 语言对应的 values-<限定符>：BCP 47 形式，如 b+zh+Hans。"""
    return 'values' if language == 'en' else 'values-b+' + language.replace('-', '+')


def android_text(text):
    """[EN] %@ -> %1$s, %n$@ -> %n$s; quotes and apostrophes escaped. [CN] %@ -> %1$s，%n$@ -> %n$s；转义引号与撇号。"""
    count = [0]

    def placeholder(match):
        count[0] += 1
        return '%' + (match.group(1) or str(count[0])) + '$s'

    text = re.sub(r'%(?:(\d+)\$)?@', placeholder, text.replace('\\"', '"'))
    return escape(text).replace("'", "\\'").replace('"', '\\"')


def files():
    for name in sorted(os.listdir(BUNDLE)):
        if not name.endswith('.lproj') or name.startswith('._'):
            continue
        language = name[:-len('.lproj')]
        table = dict(PAIR.findall(open(os.path.join(BUNDLE, name, 'CYLTabBarController.strings'), encoding='utf-8').read()))
        lines = ['<?xml version="1.0" encoding="utf-8"?>',
                 '<!-- Generated by scripts/android-library-strings.py from CYLTabBarController.bundle/%s. Do not edit. -->' % name,
                 '<!-- 由 scripts/android-library-strings.py 根据 CYLTabBarController.bundle/%s 生成，请勿手动修改。 -->' % name,
                 '<resources>']
        for resource, key in STRINGS.items():
            lines.append('    <string name="%s">%s</string>' % (resource, android_text(table.get(key, key))))
        lines += ['</resources>', '']
        yield os.path.join(RES, folder(language), FILE), '\n'.join(lines)


def main():
    stale = []
    for path, text in files():
        current = open(path, encoding='utf-8').read() if os.path.exists(path) else None
        if current == text:
            continue
        if '--check' in sys.argv:
            stale.append(path)
            continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, 'w', encoding='utf-8') as file:
            file.write(text)
    for path in stale:
        print(f'error: {os.path.relpath(path, ROOT)} is out of date: run scripts/android-library-strings.py')
    if '--check' not in sys.argv:
        print('Wrote the Android library strings from CYLTabBarController.bundle.')
    return 1 if stale else 0


if __name__ == '__main__':
    sys.exit(main())
