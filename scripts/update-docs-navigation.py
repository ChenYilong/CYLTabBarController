#!/usr/bin/env python3
"""Regenerate the navigation of the repository's Markdown documentation.

Run it after any change to README.md or docs/ (a Markdown edit, or a file or folder added, renamed or removed):

    python3 scripts/update-docs-navigation.py           # rewrite the navigation blocks
    python3 scripts/update-docs-navigation.py --check   # exit 1 if any block is out of date (CI)

Everything between <!-- navigation:start --> and <!-- navigation:end --> is generated; do not edit it by hand.
The script writes three kinds of blocks:

1. Page contents (README.md and every docs/*.md): a bilingual table with one row per heading, linking to the
   Chinese and the English heading. Paired "[CN]..." / "[EN]..." heading lines, "Chinese / English" headings and
   single-language headings are all understood. A page whose contents block does not exist yet gets one, under a
   new contents heading, right before its first level-2 heading.
2. Documentation index (README.md and docs/README.md): every docs/*.md file with its Chinese and English title.
3. Folder tree (docs/README.md): the files and folders under docs/, attachments included.
4. Class bindings. Every docs/*.md file declares the code classes it documents, right under its title:
       <!-- bound-classes: CYLPlusButton, CYLTabBarController -->      (or "none")
   The script finds each class by its "@interface Name :" declaration under CYLTabBarController/ and writes
   - into the document, between <!-- binding:start --> and <!-- binding:end -->: a bilingual table with each bound
     class and the path of its header;
   - into each bound header, right below the copyright comment, between "// docs-binding:start" and
     "// docs-binding:end": the GitHub links of the documents bound to that class.
   A moved header, a renamed document or a changed declaration is picked up on the next run; a declared class that
   cannot be found, or a document without a declaration, is an error.

Only the Python 3 standard library is used. Anchors follow GitHub's rules, so the links work on github.com.
"""

import os
import re
import sys
import urllib.parse

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS_FOLDER = "docs/"
DOCS = os.path.join(ROOT, DOCS_FOLDER.rstrip("/"))
ENCODING = "utf-8"
README_NAME = "README.md"
README = os.path.join(ROOT, README_NAME)
DOCS_INDEX = os.path.join(DOCS, README_NAME)

# The header rows of every bilingual table: a Chinese column, then an English column.
TABLE_HEADER = ("| 中文 | English |", "|:---|:---|")

START = "<!-- navigation:start -->"
END = "<!-- navigation:end -->"
NOTE = "<!-- Generated by scripts/update-docs-navigation.py; do not edit by hand. -->"

# Class bindings (see the module docstring).
SOURCES = os.path.join(ROOT, "CYLTabBarController")
GITHUB_DOCS = "https://github.com/ChenYilong/CYLTabBarController/blob/master/docs/"
BOUND_KEY = "bound-classes:"
BINDING_START = "<!-- binding:start -->"
BINDING_END = "<!-- binding:end -->"
HEADER_START = "// docs-binding:start"
HEADER_END = "// docs-binding:end"
CLASS_DECLARATION = re.compile(r"^@interface\s+(\w+)\s*:", re.M)
# A class translated to Swift keeps its Objective-C name with "@objc(Name)" right above "class Name" (docs/Swift-Migration.md).
SWIFT_CLASS_DECLARATION = re.compile(r"^@objc\((\w+)\)\s*\n(?:\s*@\w+.*\n)*\s*(?:public |open )?(?:final )?class\s+\1\b", re.M)

# Pages with more than this many level-2 and level-3 headings list level 2 only.
MAX_ROWS_WITH_LEVEL_3 = 50

FENCE = re.compile(r"^\s*(```|~~~)")
CJK = re.compile(r"[㐀-鿿豈-﫿　-〿＀-￯]")


# ---------------------------------------------------------------------------------------------------------------------
# Headings and GitHub anchors
# ---------------------------------------------------------------------------------------------------------------------

def table(rows=()):
    """A bilingual table: the header rows followed by `rows`."""
    return list(TABLE_HEADER) + list(rows)


def without_markup(text):
    """Text without Markdown links, images or HTML tags (their labels are kept)."""
    text = re.sub(r"!\[([^\]]*)\]\([^)]*\)", r"\1", text)
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", text)
    return re.sub(r"<[^>]+>", "", text)


def plain_text(text):
    """Heading text as GitHub uses it for the anchor: no Markdown links, images, HTML or code backticks."""
    return without_markup(text).replace("`", "")


def parse_heading(line):
    """(level, text) of an ATX heading such as "## Title ##", or None. Parsed without a backtracking regex."""
    level = len(line) - len(line.lstrip("#"))
    rest = line[level:]
    if not 1 <= level <= 6 or not rest[:1].isspace():
        return None
    text = rest.strip()
    closing = text.rstrip("#")
    if closing != text and (not closing or closing[-1].isspace()):
        text = closing.rstrip()
    return level, text


def marker_span(lines, start_marker, end_marker, matches=lambda line, marker: line.strip() == marker):
    """(start, end) line indexes of the first block between two marker lines, or None."""
    start = next((i for i, l in enumerate(lines) if matches(l, start_marker)), None)
    if start is None:
        return None
    end = next(i for i in range(start, len(lines)) if matches(lines[i], end_marker))
    return start, end


def github_slug(text, seen):
    """The anchor GitHub gives a heading (lowercase, punctuation removed, spaces to hyphens, -1/-2 for repeats)."""
    slug = "".join(ch for ch in plain_text(text).strip().lower() if ch.isalnum() or ch in " -_")
    slug = slug.replace(" ", "-")
    count = seen.get(slug, 0)
    seen[slug] = count + 1
    return slug if count == 0 else "{}-{}".format(slug, count)


def headings(lines):
    """(line index, level, text, anchor) for every heading outside code blocks and outside generated blocks."""
    result, seen, in_fence, in_generated = [], {}, False, False
    for index, line in enumerate(lines):
        if FENCE.match(line):
            in_fence = not in_fence
            continue
        if in_fence:
            continue
        if line.strip() == START:
            in_generated = True
        elif line.strip() == END:
            in_generated = False
        heading = parse_heading(line)
        if heading:
            level, text = heading
            anchor = github_slug(text, seen)
            if not in_generated:
                result.append((index, level, text, anchor))
    return result


def split_bilingual(text):
    """(Chinese, English) parts of a "Chinese / English" heading; (text, text) when it is not one."""
    parts = text.split(" / ")
    if len(parts) == 2 and CJK.search(parts[0]) and not CJK.search(parts[1]):
        return parts[0].strip(), parts[1].strip()
    return text, text


def heading_rows(lines):
    """One (level, Chinese, Chinese anchor, English, English anchor) per heading, pairing [CN]/[EN] lines."""
    rows, items, k = [], headings(lines), 0
    while k < len(items):
        _, level, text, anchor = items[k]
        if text.startswith("[CN]") and k + 1 < len(items) and items[k + 1][2].startswith("[EN]") \
                and items[k + 1][1] == level:
            rows.append((level, text[4:], anchor, items[k + 1][2][4:], items[k + 1][3]))
            k += 2
            continue
        chinese, english = split_bilingual(text.replace("[CN]", "").replace("[EN]", ""))
        rows.append((level, chinese, anchor, english, anchor))
        k += 1
    return rows


def cell(text):
    """Link label: like the heading, without links or HTML, but code spans kept."""
    return without_markup(text).replace("|", "\\|").strip()


def link(text, anchor):
    return "[{}](#{})".format(cell(text), anchor)


def is_contents_heading(english):
    return english.strip().lower() in ("contents", "table of contents")


# ---------------------------------------------------------------------------------------------------------------------
# Generated blocks
# ---------------------------------------------------------------------------------------------------------------------

def contents_table(lines):
    rows = [r for r in heading_rows(lines) if r[0] in (2, 3) and not is_contents_heading(r[3])]
    if len(rows) > MAX_ROWS_WITH_LEVEL_3:
        rows = [r for r in rows if r[0] == 2]
    out = table()
    for level, chinese, chinese_anchor, english, english_anchor in rows:
        indent = "&nbsp;&nbsp;&nbsp;&nbsp;↳ " if level == 3 else ""
        out.append("| {}{} | {}{} |".format(indent, link(chinese, chinese_anchor), indent, link(english, english_anchor)))
    return out


def doc_title(path):
    """(Chinese, English) title of a Markdown file, from its level-1 heading(s)."""
    with open(path, encoding=ENCODING) as handle:
        lines = handle.read().split("\n")
    titles = [r for r in heading_rows(lines) if r[0] == 1]
    if not titles:
        name = os.path.splitext(os.path.basename(path))[0].replace("-", " ")
        return name, name
    return cell(titles[0][1]), cell(titles[0][3])


def doc_files():
    # Hidden files are skipped, e.g. the "._name.md" AppleDouble files macOS writes on non-APFS volumes.
    return sorted(f for f in os.listdir(DOCS) if f.endswith(".md") and f != README_NAME and not f.startswith("."))


def docs_index_table(prefix):
    out = table()
    for name in doc_files():
        chinese, english = doc_title(os.path.join(DOCS, name))
        target = urllib.parse.quote(prefix + name)
        out.append("| [{}]({}) | [{}]({}) |".format(chinese, target, english, target))
    return out


def folder_tree(path, prefix="", extra=()):
    out = []
    entries = sorted({e for e in os.listdir(path) if not e.startswith(".")} | set(extra))
    for i, entry in enumerate(entries):
        last = i == len(entries) - 1
        full = os.path.join(path, entry)
        out.append("{}{}{}{}".format(prefix, "└── " if last else "├── ", entry, "/" if os.path.isdir(full) else ""))
        if os.path.isdir(full):
            out.extend(folder_tree(full, prefix + ("    " if last else "│   ")))
    return out


def block(body):
    return [START, NOTE, ""] + body + ["", END]


def replace_block(lines, new_block, occurrence=0):
    """Replace the occurrence-th generated block; None when the file has no such block."""
    starts = [i for i, l in enumerate(lines) if l.strip() == START]
    if len(starts) <= occurrence:
        return None
    start, end = marker_span(lines[starts[occurrence]:], START, END)
    offset = starts[occurrence]
    return lines[:offset + start] + new_block + lines[offset + end + 1:]


# ---------------------------------------------------------------------------------------------------------------------
# Pages
# ---------------------------------------------------------------------------------------------------------------------

def uses_paired_headings(lines):
    return any(l.startswith("## [CN]") for l in lines)


def insert_contents_section(lines):
    """Add a contents heading and an empty block right before the first level-2 heading (or at the end)."""
    first = next((i for i, l in enumerate(lines) if l.startswith("## ")), len(lines))
    if uses_paired_headings(lines):
        section = ["## [CN]目录", "## [EN]Contents", ""]
    else:
        section = ["## 目录 / Contents", ""]
    return lines[:first] + section + [START, END, ""] + lines[first:]


def contents_heading_index(lines):
    """Line index of the level-2 Contents heading (its English part), or None."""
    for index, level, text, _ in headings(lines):
        english = text[4:] if text.startswith("[EN]") else split_bilingual(text)[1]
        if level == 2 and is_contents_heading(english):
            return index
    return None


def table_end_after(lines, index):
    """End (exclusive) of the table that follows line `index`, skipping blank and comment lines; index + 1 if none."""
    i = index + 1
    while i < len(lines) and (not lines[i].strip() or lines[i].lstrip().startswith("<!--")):
        i += 1
    if i >= len(lines) or not lines[i].startswith("|"):
        return index + 1
    while i < len(lines) and lines[i].startswith("|"):
        i += 1
    return i


def adopt_handwritten_contents(lines):
    """Turn an existing hand-written contents table (under a Contents heading) into a generated block."""
    index = contents_heading_index(lines)
    if index is None:
        return None
    return lines[:index + 1] + ["", START, END] + lines[table_end_after(lines, index):]


def update_page(path, extra_blocks=()):
    with open(path, encoding=ENCODING) as handle:
        original = handle.read()
    lines = original.split("\n")
    if START not in original:
        lines = adopt_handwritten_contents(lines) or insert_contents_section(lines)
    lines = replace_block(lines, block(contents_table(lines)))
    for occurrence, body in extra_blocks:
        replaced = replace_block(lines, block(body), occurrence)
        if replaced is not None:
            lines = replaced
    return original, "\n".join(lines)


def readme_extra_blocks():
    """The README's second block: the documentation index, right after its contents block."""
    body = docs_index_table(DOCS_FOLDER)
    # First row: the full index page, which also shows the folder layout. 第一行：完整索引页（含目录结构）。
    index_link = DOCS_FOLDER + README_NAME
    body.insert(2, "| [文档导航（全部文档与目录结构）]({0}) | [Documentation index (all documents and folder layout)]({0}) |"
                .format(index_link))
    return [(1, body)]


def ensure_readme_index_block(text):
    """Add the documentation index block after the README's contents block if it is missing."""
    if text.count(START) >= 2:
        return text
    lines = text.split("\n")
    end = next(i for i, l in enumerate(lines) if l.strip() == END)
    section = ["", "## [CN]文档索引", "## [EN]Documentation index", "", START, END]
    return "\n".join(lines[:end + 1] + section + lines[end + 1:])


def docs_index_page():
    lines = ["# [CN]文档导航", "# [EN]Documentation", "",
             *TABLE_HEADER,
             "| 本页列出 `docs/` 中的全部文档与目录结构，由 `scripts/update-docs-navigation.py` 自动生成；"
             "文档或目录有任何变动时会自动更新。返回 [README](../README.md)。 | "
             "This page lists every document in `docs/` and its folder layout. It is generated by "
             "`scripts/update-docs-navigation.py` and updated whenever a document or folder changes. "
             "Back to the [README](../README.md). |", "",
             "## [CN]文档", "## [EN]Documents", ""] + block(docs_index_table("")) + [
             "", "## [CN]目录结构", "## [EN]Folder layout", "",
             *TABLE_HEADER,
             "| 附件放在 Markdown 文件旁边的 `assets/` 中，用最短的相对路径引用（见 [CLAUDE.md](../CLAUDE.md)）。 | "
             "Attachments live in `assets/` next to their Markdown file and are linked with the shortest relative "
             "path (see [CLAUDE.md](../CLAUDE.md)). |", ""] + block(["```text", DOCS_FOLDER] + folder_tree(DOCS, extra=(README_NAME,)) + ["```"])
    return "\n".join(lines) + "\n"



# ---------------------------------------------------------------------------------------------------------------------
# Class bindings
# ---------------------------------------------------------------------------------------------------------------------

class BindingError(Exception):
    pass


def source_headers():
    """(path relative to the repository, text) of every header under CYLTabBarController/, SPM shims excluded."""
    for directory, folders, files in os.walk(SOURCES):
        folders[:] = sorted(f for f in folders if f != "include" and not f.startswith("."))
        for name in sorted(f for f in files if f.endswith(".h") and not f.startswith(".")):
            path = os.path.join(directory, name)
            with open(path, encoding=ENCODING, errors="replace") as handle:
                yield os.path.relpath(path, ROOT), handle.read()


def swift_sources():
    """(path relative to the repository, text) of every Swift file under CYLTabBarController/."""
    for directory, folders, files in os.walk(SOURCES):
        folders[:] = sorted(f for f in folders if not f.startswith("."))
        for name in sorted(f for f in files if f.endswith(".swift") and not f.startswith(".")):
            path = os.path.join(directory, name)
            with open(path, encoding=ENCODING, errors="replace") as handle:
                yield os.path.relpath(path, ROOT), handle.read()


def class_headers(headers):
    """Class name -> header path for every "@interface Name :" declaration in `headers`.

    A class translated to Swift ("@objc(Name)" above "class Name" in a Swift file) is bound to the header of the same
    name, which stays for Objective-C callers; without such a header, to the Swift file itself.
    """
    found = {}
    by_file_name = {}
    for path, text in headers:
        by_file_name.setdefault(os.path.basename(path), path)
        for class_name in CLASS_DECLARATION.findall(text):
            found.setdefault(class_name, path)
    for path, text in swift_sources():
        for class_name in SWIFT_CLASS_DECLARATION.findall(text):
            found.setdefault(class_name, by_file_name.get(class_name + ".h", path))
    return found


def bound_declaration(line):
    """The value of a "<!-- bound-classes: ... -->" line, or None. Parsed without a backtracking regex."""
    text = line.strip()
    if not (text.startswith("<!--") and text.endswith("-->")):
        return None
    inner = text[4:-3].strip()
    return inner[len(BOUND_KEY):].strip() if inner.startswith(BOUND_KEY) else None


def bound_classes(lines, name):
    for line in lines:
        value = bound_declaration(line)
        if value is not None:
            return [] if value.lower() == "none" else [c.strip() for c in value.split(",") if c.strip()]
    raise BindingError("{}{}: missing the <!-- bound-classes: ... --> declaration under its title".format(DOCS_FOLDER, name))


def binding_rows(classes, headers, name):
    rows = table()
    if not classes:
        rows.append("| 本文档不绑定代码类。 | This document is not bound to a code class. |")
        return rows
    for class_name in classes:
        header = headers.get(class_name)
        if not header:
            raise BindingError("{}{}: bound class {} is not declared in any header under CYLTabBarController/"
                               .format(DOCS_FOLDER, name, class_name))
        target = "../" + urllib.parse.quote(header)
        rows.append("| 绑定的代码类 `{0}`：[`{1}`]({2}) | Bound to the class `{0}`: [`{1}`]({2}) |"
                    .format(class_name, header, target))
    return rows


def apply_binding_block(lines, rows):
    """Write the binding block right after the bound-classes declaration."""
    new_block = [BINDING_START, NOTE, ""] + rows + ["", BINDING_END]
    span = marker_span(lines, BINDING_START, BINDING_END)
    if span:
        return lines[:span[0]] + new_block + lines[span[1] + 1:]
    declaration = next(i for i, l in enumerate(lines) if bound_declaration(l) is not None)
    return lines[:declaration + 1] + new_block + lines[declaration + 1:]


def header_block(docs):
    out = [HEADER_START + " (generated by scripts/update-docs-navigation.py; do not edit by hand)",
           "// [EN] Documentation bound to this class:",
           "// [CN] 与此类绑定的文档："]
    for name, chinese, english in docs:
        out.append("//   - {} / {}".format(english, chinese) if chinese != english else "//   - {}".format(english))
        out.append("//     " + GITHUB_DOCS + urllib.parse.quote(name))
    out.append(HEADER_END)
    return out


def update_header(text, docs):
    """Replace, add or remove the docs-binding block of a header (below its leading copyright comment)."""
    lines = text.split("\n")
    span = marker_span(lines, HEADER_START, HEADER_END, lambda line, marker: line.startswith(marker))
    if span:
        start, end = span
        if end + 1 < len(lines) and not lines[end + 1].strip():
            end += 1
        lines = lines[:start] + lines[end + 1:]
    if not docs:
        return "\n".join(lines)
    i = 0
    while i < len(lines) and lines[i].startswith("//"):
        i += 1
    while i < len(lines) and not lines[i].strip():
        i += 1
    return "\n".join(lines[:i] + header_block(docs) + [""] + lines[i:])


def bind(doc_texts):
    """Doc name -> updated text, and header path -> (old, new) text, for every class binding."""
    sources = list(source_headers())
    headers = class_headers(sources)
    by_header, new_docs = {}, {}
    for name, text in doc_texts.items():
        lines = text.split("\n")
        classes = bound_classes(lines, name)
        new_docs[name] = "\n".join(apply_binding_block(lines, binding_rows(classes, headers, name)))
        chinese, english = doc_title(os.path.join(DOCS, name))
        for class_name in classes:
            entries = by_header.setdefault(headers[class_name], [])
            # A document binding several classes of the same header is listed once.
            if (name, chinese, english) not in entries:
                entries.append((name, chinese, english))
    # Every header that has, or should have, a binding block.
    targets = set(by_header) | {path for path, text in sources if HEADER_START in text}
    header_results = {}
    for header in sorted(targets):
        path = os.path.join(ROOT, header)
        with open(path, encoding=ENCODING) as handle:
            old = handle.read()
        header_results[path] = (old, update_header(old, sorted(by_header.get(header, []))))
    return new_docs, header_results


def main():
    check = "--check" in sys.argv[1:]
    results = {}

    # docs/README.md: the documentation index and the folder tree, regenerated as a whole.
    old_index = open(DOCS_INDEX, encoding=ENCODING).read() if os.path.exists(DOCS_INDEX) else ""
    results[DOCS_INDEX] = (old_index, docs_index_page())

    # README.md: its contents block, then the documentation index block.
    with open(README, encoding=ENCODING) as handle:
        original_readme = handle.read()
    lines = original_readme.split("\n")
    if START not in original_readme:
        lines = adopt_handwritten_contents(lines) or insert_contents_section(lines)
    lines = ensure_readme_index_block("\n".join(lines)).split("\n")
    lines = replace_block(lines, block(contents_table(lines)))
    for occurrence, body in readme_extra_blocks():
        lines = replace_block(lines, block(body), occurrence)
    results[README] = (original_readme, "\n".join(lines))

    # Every other document in docs/: its own contents, then its class binding (and the bound headers).
    for name in doc_files():
        path = os.path.join(DOCS, name)
        results[path] = update_page(path)
    try:
        bound_docs, header_results = bind({name: results[os.path.join(DOCS, name)][1] for name in doc_files()})
    except BindingError as error:
        print("error: " + str(error))
        return 1
    for name, text in bound_docs.items():
        path = os.path.join(DOCS, name)
        results[path] = (results[path][0], text)
    results.update(header_results)

    stale = [path for path, (old, new) in results.items() if old != new]
    if check:
        for path in stale:
            print("navigation or binding out of date: " + os.path.relpath(path, ROOT))
        if stale:
            print("Run: python3 scripts/update-docs-navigation.py")
        return 1 if stale else 0
    for path in stale:
        with open(path, "w", encoding=ENCODING) as handle:
            handle.write(results[path][1])
        print("updated " + os.path.relpath(path, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
